function getText(lang, key) {
  return key.split('.').reduce((obj, part) => obj?.[part], translations[lang]) || '';
}

function detectInitialLanguage() {
  const saved = localStorage.getItem('flipbookLanguage');
  if (saved === 'zh' || saved === 'en') return saved;
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return languages.some((lang) => String(lang).toLowerCase().startsWith('zh')) ? 'zh' : 'en';
}

function applyLanguage(lang) {
  const safeLang = lang === 'en' ? 'en' : 'zh';
  document.documentElement.lang = safeLang === 'zh' ? 'zh-CN' : 'en';
  document.body.dataset.lang = safeLang;
  document.title = translations[safeLang].meta.title;
  document.querySelector('[data-i18n-meta="description"]')?.setAttribute('content', translations[safeLang].meta.description);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const text = getText(safeLang, element.dataset.i18n);
    if (text) element.textContent = text;
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    element.dataset.i18nAttr.split(',').forEach((entry) => {
      const [attr, key] = entry.split(':').map((part) => part.trim());
      const value = getText(safeLang, key);
      if (attr && value) element.setAttribute(attr, value);
    });
  });

  document.querySelectorAll('.lang-button').forEach((button) => {
    const active = button.dataset.lang === safeLang;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

const initialLanguage = detectInitialLanguage();
applyLanguage(initialLanguage);

const menuButton = document.querySelector('.menu-button');
const mobileNav = document.querySelector('.mobile-nav');

menuButton?.addEventListener('click', () => {
  const open = mobileNav.classList.toggle('open');
  document.body.classList.toggle('nav-open', open);
  menuButton.setAttribute('aria-expanded', String(open));
});

mobileNav?.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => {
    mobileNav.classList.remove('open');
    document.body.classList.remove('nav-open');
    menuButton?.setAttribute('aria-expanded', 'false');
  });
});

document.querySelectorAll('.lang-button').forEach((button) => {
  button.addEventListener('click', () => {
    const nextLang = button.dataset.lang === 'en' ? 'en' : 'zh';
    localStorage.setItem('flipbookLanguage', nextLang);
    applyLanguage(nextLang);
  });
});

if ('IntersectionObserver' in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 },
  );
  document.querySelectorAll('.reveal').forEach((el) => observer.observe(el));
} else {
  document.querySelectorAll('.reveal').forEach((el) => el.classList.add('visible'));
}

const album = document.querySelector('.hero-album');
const track = album?.querySelector('.album-track');
const slides = album ? [...album.querySelectorAll('.album-slide')] : [];
const dots = album ? [...album.querySelectorAll('.dot')] : [];
const prevBtn = album?.querySelector('.album-nav.prev');
const nextBtn = album?.querySelector('.album-nav.next');

const lightbox = document.getElementById('lightbox');
const lightboxImage = lightbox?.querySelector('.lightbox-image');
const lightboxClose = lightbox?.querySelector('.lightbox-close');
const lightboxPrev = lightbox?.querySelector('.lightbox-nav.prev');
const lightboxNext = lightbox?.querySelector('.lightbox-nav.next');

let currentIndex = 0;

function renderAlbum(index) {
  if (!track || !slides.length) return;
  const max = slides.length - 1;
  currentIndex = Math.max(0, Math.min(index, max));
  slides.forEach((slide, i) => slide.classList.toggle('is-active', i === currentIndex));
  dots.forEach((dot, i) => dot.classList.toggle('is-active', i === currentIndex));
}

function openLightbox(index) {
  if (!lightbox || !lightboxImage || !slides.length) return;
  renderAlbum(index);
  lightboxImage.src = slides[currentIndex].dataset.src || '';
  lightbox.classList.add('open');
  lightbox.setAttribute('aria-hidden', 'false');
}

function closeLightbox() {
  if (!lightbox || !lightboxImage) return;
  lightbox.classList.remove('open');
  lightbox.setAttribute('aria-hidden', 'true');
  lightboxImage.src = '';
}

prevBtn?.addEventListener('click', () => renderAlbum(currentIndex - 1 < 0 ? slides.length - 1 : currentIndex - 1));
nextBtn?.addEventListener('click', () => renderAlbum(currentIndex + 1 > slides.length - 1 ? 0 : currentIndex + 1));
dots.forEach((dot, idx) => dot.addEventListener('click', () => renderAlbum(idx)));
slides.forEach((slide, idx) => slide.addEventListener('click', () => openLightbox(idx)));

lightboxClose?.addEventListener('click', closeLightbox);
lightbox?.addEventListener('click', (event) => {
  if (event.target === lightbox) closeLightbox();
});

lightboxPrev?.addEventListener('click', () => {
  if (!slides.length) return;
  renderAlbum(currentIndex - 1 < 0 ? slides.length - 1 : currentIndex - 1);
  if (lightboxImage) lightboxImage.src = slides[currentIndex].dataset.src || '';
});

lightboxNext?.addEventListener('click', () => {
  if (!slides.length) return;
  renderAlbum(currentIndex + 1 > slides.length - 1 ? 0 : currentIndex + 1);
  if (lightboxImage) lightboxImage.src = slides[currentIndex].dataset.src || '';
});

window.addEventListener('keydown', (event) => {
  if (!lightbox?.classList.contains('open')) return;
  if (event.key === 'Escape') closeLightbox();
  if (event.key === 'ArrowLeft') lightboxPrev?.click();
  if (event.key === 'ArrowRight') lightboxNext?.click();
});

renderAlbum(0);
